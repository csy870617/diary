function spaceStart(core) {
    for (const [wrong, right] of SPACE_STARTS) {
        if (!core.startsWith(wrong)) continue;
        const head = right.split(' ')[0];
        return { to: right + core.slice(wrong.length), why: `${topic(head)} 뒷말과 띄어 씁니다` };
    }
    // '-다 보니·-ㄹ까 봐·-나 보다·-는 데다' (쳐다보다·내다보다처럼 한 낱말인 것은 그대로)
    let m = /^(.*[가-힣]다)(보니까|보니|보면)$/.exec(core);
    if (m && !/(쳐|내|내려|올려|들여|바라|건너)다$/.test(m[1])) return { to: m[1] + ' ' + m[2], why: "'-다 보니'의 '보다'는 띄어 씁니다" };
    m = /^(.*([가-힣])까)(봐|봐서|봐요)$/.exec(core);
    if (m && endsWithL(m[2])) return { to: m[1] + ' ' + m[3], why: "'-ㄹ까 봐'의 '봐'는 띄어 씁니다" };
    m = /^(.*([가-힣])나|.*([가-힣])가)(보다|봐|봐요|보네|봅니다|보구나)$/.exec(core);
    if (m && ((m[2] && jongOf(m[2]) === JONG_SS) || (m[3] && (jongOf(m[3]) === JONG_N || /[는은]/.test(m[3]))))) return { to: m[1] + ' ' + m[4], why: "'-나 보다·-ㄴ가 보다'의 '보다'는 띄어 씁니다" };
    m = /^(.*([가-힣]))데다(가)?$/.exec(core);
    if (m && m[1].length >= 2 && (/[는은던]$/.test(m[1]) || jongOf(m[2]) === JONG_N)) return { to: m[1] + ' 데다' + (m[3] || ''), why: "'-는 데다(가)'의 '데'는 의존 명사라 띄어 씁니다" };
    return null;
}

function adverbFix(core) {
    const m = /^(.+?)(도)?$/.exec(core);
    const to = m && ADVERB_FIXES[m[1]];
    if (!to) return null;
    return { to: to + (m[2] || ''), why: `'${to}'가 맞는 말입니다 (부사의 '-이·-히')` };
}

