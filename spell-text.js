/** 영어 낱말에 사전이 권한 말 가운데 흔한 오타 꼴로 고친 것 하나 (확실하지 않으면 null) */
export function pickEnglish(word, suggestions) {
    // 줄임말에 작은따옴표만 빠뜨린 것 (dont → don't)
    const bare = (x) => x.replace(/['’]/g, '');
    const quoted = suggestions.find(s => /'/.test(s) && !/['’]/.test(word) && bare(s).toLowerCase() === word.toLowerCase());
    if (quoted) return matchCase(word, quoted);
    const w = word.toLowerCase();
    if (w.length < 4) return null;   // 짧은 말은 줄임말·이름이 많아 고치지 않는다
    for (const s of suggestions) {
        if (/[\s-]/.test(s) || s.toLowerCase() === w) continue;
        const t = s.toLowerCase();
        // 첫 글자가 다르면 다른 말로 본다 (vlog → clog). 앞 두 글자가 바뀐 것(hte → the)만 받는다
        if (t[0] !== w[0] && !(t[0] === w[1] && t[1] === w[0])) continue;
        const d = letterDistance(w, t);
        const collapse = (x) => x.replace(/(.)\1+/g, '$1');
        if ((d === 1 && (w.length >= 5 || typoLike(w, t))) || (d === 2 && w.length >= 8 && letterDistance(collapse(w), collapse(t)) <= 1)) return matchCase(word, s);
    }
    return null;
}

/** 네 글자 낱말의 흔한 오타: 이웃 글자 바뀜·겹글자·모음 하나 */
function typoLike(a, b) {
    if (a.length === b.length) {
        const diff = [...a].map((ch, i) => ch !== b[i] ? i : -1).filter(i => i >= 0);
        if (diff.length === 2 && diff[1] === diff[0] + 1 && a[diff[0]] === b[diff[1]] && a[diff[1]] === b[diff[0]]) return true;
        return diff.length === 1 && /[aeiou]/.test(a[diff[0]]) && /[aeiou]/.test(b[diff[0]]);
    }
    const [long, short] = a.length > b.length ? [a, b] : [b, a];
    for (let i = 0; i < long.length; i++) {
        if (long.slice(0, i) + long.slice(i + 1) === short) return i > 0 && long[i] === long[i - 1];
    }
    return false;
}

/** 원래 낱말이 대문자로 시작하면 고친 말도 대문자로 */
function matchCase(word, s) {
    return /^[A-Z]/.test(word) && /^[a-z]/.test(s) ? s[0].toUpperCase() + s.slice(1) : s;
}

/** 영어 고친 곳의 이유 */
function englishWhy(from, to) {
    if (/'/.test(to) && !/['’]/.test(from)) return "줄여 쓴 말에는 작은따옴표(')를 씁니다";
    const a = from.toLowerCase(), b = to.toLowerCase();
    if (a.length !== b.length) return a.length > b.length ? '글자를 더 썼습니다' : '글자를 빠뜨렸습니다';
    return '철자가 틀렸습니다';
}

/** 이 영어 낱말을 검사할까? — 대문자로만 쓴 말(QT·CCM)·문장 가운데의 대문자 이름은 건너뛴다 */
function checkEnglish(w, text) {
    const c = w.core;
    if (c.length < 3 || c === c.toUpperCase()) return false;
    if (/[A-Z]/.test(c.slice(1))) return false;
    if (/^[A-Z]/.test(c)) {
        const before = text.slice(0, w.a).replace(/\s+$/, '');
        if (before && !/[.!?。]$/.test(before)) return false;   // 문장 처음이 아니면 이름으로 본다
    }
    return true;
}

// 마디를 끝내는 이음 꼴 (듣고·와서·하며·하니·했는데·하지만·하다가·하려고)
const CLAUSE_END = /(고|서|며|면|니|는데|은데|지만|다가|려고|도록|니까|자|든지)$/;
// '-을/-를'로 끝나도 목적어가 아닌 말 (가을 햇살 · 마을 사람 · 다를 바 없다)
const NOT_OBJECT = /(가을|마을|노을|고을|다를|모를)$/;

/**
 * i번째 낱말이 속한 마디(앞의 '-고·-서·-며' 뒤)에서 그 앞에 목적어('-을/-를')가 있는가.
 * ('소식을 듣고 놀랬다'의 '소식을'은 '듣고'의 것이라 '놀랬다'의 목적어가 아니다)
 * cores: 줄의 낱말들, same(k): k번째 낱말이 i번째와 같은 문장인가
 */
export function objectBeforeIn(cores, i, same) {
    let from = i;
    while (from > 0 && same(from - 1) && !CLAUSE_END.test(cores[from - 1])) from--;
    for (let k = from; k < i; k++) if (/[가-힣][을를]$/.test(cores[k]) && !NOT_OBJECT.test(cores[k])) return true;
    return false;
}

/** 고친 곳의 종류 — 띄어쓰기만 바뀌었으면 '띄어쓰기', 그 밖에는 규칙이 정한 종류(표준어·문맥)나 '맞춤법' */
function kindOf(from, to, kind) {
    const k = spellKind(from, to);
    return k === '맞춤법' && kind ? kind : k;
}

/**
 * 줄들을 검사한다.
 * lines: [{ id, text }]
 * dict.lookup({ ko: [낱말], en: [낱말] }) → { ko: { 낱말: 판정 }, en: {…} }
 *   판정: null(사전에 있는 말) | false(사전에 없지만 고칠 말을 확실히 모른다 — 이름 등) | { to, why, kind? }
 * skip(낱말): 검사하지 않을 말인가 (사용자가 사전에 넣은 말 등)
 * → [{ id, a, b, from, to, type, why, word, src: 'rule'|'dict' }] (a, b: 그 줄에서의 위치)
 *   type: '맞춤법' | '띄어쓰기' | '문장 부호' | '표준어' | '문맥'
 */
export async function checkLines(lines, dict, { skip = () => false } = {}) {
    const fixes = [];
    const ask = { ko: new Set(), en: new Set() };
    const later = [];   // 규칙으로 고치지 않은 낱말 — 사전에 물은 뒤 처리한다
    const checked = [];   // 사전으로 확인한 뒤에 고칠 두 낱말 규칙
    const joins = [];     // 붙여 써야 할지 사전으로 확인할 두 낱말 (확인되면 두 낱말 따로 고치는 것은 버린다)
    const refine = [];    // 규칙으로 띄운 뒤에도 붙어 있는 조각 — 사전으로 더 나눠 본다 (잘정착하실수 → 잘 정착하실 수)
    for (const line of lines) {
        const text = line.text;
        const words = wordsOf(text);
        const code = (text.match(/[{};=<>|&]|=>|\(\)/g) || []).length >= 3;   // 프로그램 코드처럼 보이는 줄의 영어는 검사하지 않는다
        const used = new Set();
        // 문장 나누기 — 문맥 규칙은 같은 문장 안의 말만 본다
        const sentenceOf = [];
        let sid = 0;
        words.forEach((w, i) => { sentenceOf[i] = sid; if (/[.!?。…]["'”’)]*$/.test(text.slice(w.a, w.b))) sid++; });
        if (!code) for (const f of punctuationFixes(text)) fixes.push({ id: line.id, ...f, type: '띄어쓰기', src: 'rule' });
        for (const r of pairRules(words)) {
            if (used.has(r.i) || used.has(r.j)) continue;
            const a = words[r.i].ca, b = words[r.j].cb;
            const fix = { id: line.id, a, b, from: text.slice(a, b), to: r.to, type: spellKind(text.slice(a, b), r.to), why: r.why, src: 'rule' };
            if (r.valid || r.invalid) {
                [...(r.valid || []), ...(r.invalid || [])].forEach(x => ask.ko.add(x));
                checked.push({ fix, valid: r.valid || [], invalid: r.invalid || [] });
            } else fixes.push(fix);
            used.add(r.i); used.add(r.j);
        }
        for (const c of joinCandidates(words)) {
            if (used.has(c.i) || used.has(c.j) || skip(words[c.i].core) || skip(words[c.j].core)) continue;
            const a = words[c.i].ca, b = words[c.j].cb;
            [...c.valid, ...c.invalid].forEach(x => ask.ko.add(x));
            joins.push({ fix: { id: line.id, a, b, from: text.slice(a, b), to: c.to, type: '띄어쓰기', why: c.why, src: 'rule' }, valid: c.valid, invalid: c.invalid });
        }
        words.forEach((w, i) => {
            const man = !w.lang && /^([0-9]+(년|달|개월|주|주일|일|시간|분|초))만(에|이다|이야|이네|인데|이에요|입니다|이지|이구나)$/.exec(w.core);
            if (man && !used.has(i)) {
                fixes.push({ id: line.id, a: w.ca, b: w.cb, from: w.core, to: man[1] + ' 만' + man[3], type: '띄어쓰기', why: "지난 시간을 나타내는 '만'은 의존 명사라 띄어 씁니다", src: 'rule' });
                return;
            }
            if (used.has(i) || !w.lang || skip(w.core)) return;
            if (/:\/\/|www\.|@/.test(text.slice(w.a, w.b))) return;   // 주소·전자우편
            if (w.lang === 'ko' && w.core.length >= 3 && /^[일이삼사오육칠팔구십백천만억조]+$/.test(w.core)) return;   // 한자어 수 (백이십만)
            // 종류: 맞춤법·띄어쓰기·문장 부호(고친 모양으로 정한다)·표준어·문맥(규칙이 정한다)
            const rule = (to, why, kind) => fixes.push({ id: line.id, a: w.ca, b: w.cb, from: w.core, to, type: kindOf(w.core, to, kind), why, src: 'rule' });
            if (w.lang === 'ko') {
                const near = (k) => (words[k] && sentenceOf[k] === sentenceOf[i] ? words[k].core : '');
                // 쉼표로 끊긴 뒷말은 이 낱말과 이어지는 말이 아니다 (싶은데, 비용이 → '싶은 데'가 아니다)
                const nextWord = /,/.test(text.slice(w.cb, w.b)) ? '' : near(i + 1);
                const r = fixKoreanWord(w.core, near(i - 1), nextWord);
                if (r && r.to.replace(/ /g, '') === w.core) {
                    const pieces = r.to.split(' ').filter(x => x.length >= 4);
                    if (pieces.length) {
                        pieces.forEach(x => ask.ko.add(x));
                        refine.push({ line, w, to: r.to, why: r.whys.join(' · '), kind: r.kind });
                        return;
                    }
                }
                if (r) { rule(r.to, r.whys.join(' · '), r.kind); return; }
                const others = words.filter((o, k) => k !== i && sentenceOf[k] === sentenceOf[i]).map(o => o.core);
                const objectBefore = objectBeforeIn(words.map(o => o.core), i, k => sentenceOf[k] === sentenceOf[i]);
                const c = contextFix(w.core, { prev: near(i - 1), prev2: near(i - 2), prev3: near(i - 3), next: nextWord, others, objectBefore });
                if (c) { rule(c.to, c.why, c.kind); return; }
                if (w.core.length < 2 || ARCHAIC.test(w.core)) return;   // 한 글자 낱말·옛말 꼴은 사전에 묻지 않는다
                ask.ko.add(w.core);
                const alt = copulaEnding(w.core);
                if (alt) [alt.stem + '의', alt.stem + '을'].forEach(x => ask.ko.add(x));
                later.push({ line, w, lang: 'ko', alt });
                return;
            }
            const low = w.core.toLowerCase();
            const fix = EN_FIX[low.replace(/’/g, "'")];
            // 홀로 쓴 'i'는 앞뒤에 영어 낱말이 있을 때만 '나'로 본다 (목록의 i 같은 것은 그대로)
            const inEnglish = [words[i - 1], words[i + 1]].some(n => n && n.lang === 'en' && n.core.length >= 2);
            if (fix && w.core.replace(/’/g, "'") !== fix && (low !== 'i' || inEnglish)) {
                const to = fix[0] === 'I' ? fix : matchCase(w.core, fix);
                rule(w.core.includes('’') ? to.replace(/'/g, '’') : to, fix[0] === 'I' ? "'나'를 뜻하는 I는 늘 대문자로 씁니다" : englishWhy(w.core, to));
            } else if (EN_SPLIT[low]) {
                let to = EN_SPLIT[low];
                if (/^[A-Z]/.test(w.core)) to = to[0].toUpperCase() + to.slice(1);
                rule(to, '두 낱말로 띄어 씁니다', '띄어쓰기');
            } else if (!code && !EN_SKIP.has(low) && checkEnglish(w, text)) {
                const q = w.core.replace(/’/g, "'");
                ask.en.add(q);
                later.push({ line, w, lang: 'en', q });
            }
        });
    }
    if (later.length || checked.length || joins.length || refine.length) {
        const res = await dict.lookup({ ko: [...ask.ko], en: [...ask.en] });
        const known = (x) => res.ko && res.ko[x] === null;
        for (const c of checked) if (c.valid.every(known) && !c.invalid.some(known)) fixes.push(c.fix);
        const joined = [];   // 붙여 쓰라고 한 자리 — 그 안의 낱말은 따로 고치지 않는다
        for (const c of joins) {
            const { fix } = c;
            if (joined.some(x => x.id === fix.id && x.a < fix.b && fix.a < x.b)) continue;
            if (c.valid.every(known) && !c.invalid.some(known)) { fixes.push(fix); joined.push(fix); }
        }
        for (const { line, w, to, why, kind } of refine) {
            let more = false;
            const parts = to.split(' ').map(x => {
                const d = x.length >= 4 && res.ko && res.ko[x];
                if (d && d.to && d.to.replace(/ /g, '') === x) { more = true; return d.to; }
                return x;
            });
            const all = parts.join(' ');
            fixes.push({ id: line.id, a: w.ca, b: w.cb, from: w.core, to: all, type: kindOf(w.core, all, kind), why: more ? why + ' · 낱말과 낱말 사이는 띄어 씁니다' : why, src: 'rule' });
        }
        for (const { line, w, lang, q, alt } of later) {
            if (joined.some(x => x.id === line.id && x.a <= w.ca && w.cb <= x.b)) continue;
            const d = lang === 'ko' ? res.ko && res.ko[w.core] : res.en && res.en[q];
            if (d === null || d === undefined) continue;   // 사전에 있는 말
            if (alt) {
                if (!known(alt.stem + '의') || !known(alt.stem + '을')) continue;   // 앞말이 명사가 아니다 (이름 + '-이' 등)
                fixes.push({ id: line.id, a: w.ca, b: w.cb, from: w.core, to: alt.to, type: spellKind(w.core, alt.to), why: alt.why, src: 'rule' });
                continue;
            }
            if (!d) continue;   // 사전에 없지만 확실히 고칠 말이 없다 — 이름 등은 그대로 둔다
            const to = lang === 'en' && w.core.includes('’') ? d.to.replace(/'/g, '’') : d.to;
            fixes.push({ id: line.id, a: w.ca, b: w.cb, from: w.core, to, type: kindOf(w.core, to, d.kind), why: d.why, word: w.core, src: 'dict', basis: d.basis });
        }
    }
    fixes.sort((x, y) => x.id - y.id || x.a - y.a);
    return fixes;
}

