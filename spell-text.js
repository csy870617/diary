/** 문맥을 보고 고칠 말 → { to, why, kind: '문맥' } | null */
export function contextFix(core, ctx) {
    const { prev = '', prev2 = '', prev3 = '', next = '', others = [], objectBefore = false } = ctx;
    const out = (to, why) => (to && to !== core ? { to, why, kind: '문맥' } : null);
    const before = [prev, prev2, prev3];

    // 들르다: '마트에 들렸다' → 들렀다 ('소리가 들렸다'처럼 듣는 뜻이면 그대로)
    if (/^들(렸|려)/.test(core) && !others.some(x => SOUND_SUBJECT.test(x))) {
        const place = [prev, prev2].some(x => /(에|에도|에는|에만)$/.test(x) && PLACES.has(x.replace(/(에|에도|에는|에만)$/, '')));
        if (place) return out(swapStem(core, [['들렸', '들렀'], ['들려', '들러']]), "'들르다'(잠깐 들어가 머물다)는 '들렀다·들러'로 씁니다 ('들렸다'는 소리가 들린 것)");
    }
    // 헷갈리는 말 표 (바치다·받치다, 매다·메다, 띠다·띄다 …) — 앞의 세 낱말 안에 짝이 되는 말이 있을 때만
    const scripture = others.some(x => ARCHAIC.test(x));   // 성경 구절은 본문 그대로 둔다
    for (const c of scripture ? [] : CONFUSABLES) {
        if (!c.re.test(core)) continue;
        // 주어를 보고 고르는 짝(햇빛이 비치다 · 문이 닫히다 · 눈이 부시다 …)은 '-을/-를'을 받으면 본디 말이 맞다
        // (달이 호수를 비춘다 · 빛이 어둠을 부순다 · 햇살이 방 안을 비춘다)
        if (c.subj && objectBefore) continue;
        if (!before.some(x => x && c.near.test(x))) continue;
        const to = swapStem(core, c.swap);
        if (to && to !== core) return out(to, c.why);
    }
    // 체(척)·채(그대로): '모르는 채 했다' → 체, '신은 체로' → 채로
    const adnominal = /[가-힣]$/.test(prev) && (jongOf(prev[prev.length - 1]) === JONG_N || /[는던]$/.test(prev));
    if (adnominal && core === '채' && /^(하|했|해|한|할|합|함)/.test(next)) return out('체', "그럴듯하게 꾸미는 것은 '체'(척)입니다 ('채'는 그 상태 그대로)");
    if (adnominal && /^체(로|로는|로도)$/.test(core)) return out('채' + core.slice(1), "그 상태 그대로인 것은 '채'입니다 ('체'는 척)");
    // 한참(오랫동안)·한창(가장 활발할 때)
    if (core === '한창' && /^(기다|걸었|걸어|걷|동안|후|뒤|만에|있다가|지나|생각|고민|웃었|울었|찾았|헤맸|헤매|서|앉아|쳐다)/.test(next)) {
        return out('한참', "시간이 꽤 지나는 동안은 '한참'입니다 ('한창'은 가장 활발할 때)");
    }
    if (core === '한참' && /^(중|때|나이|일할|바쁠|자랄|피어|공사|진행|성수기|젊을|무르익)/.test(next)) {
        return out('한창', "가장 활발하거나 무르익은 때는 '한창'입니다 ('한참'은 꽤 오랫동안)");
    }
    // 일절(아주·전혀, 부정과 함께)·일체(모든 것)
    if (core === '일체' && (/^(안|않|못|없|금지|사절|말|하지|먹지|마시지|연락하지|받지|허용하지|입에|하면|하지)/.test(next) || (/지$/.test(next) && others.some(x => /^(않|못|말)/.test(x))))) {
        return out('일절', "'전혀·절대로'의 뜻으로 부정하는 말과 함께 쓸 때는 '일절'입니다");
    }
    // '-는 데' + 걸린 시간·든 돈: '이 일을 하는데 3시간 걸렸다' → '하는 데' (같은 문장에 '걸리다·들다'가 있을 때만)
    if (/^.+[는은]데$/.test(core) && /^([0-9]+ ?(시간|분|초|일|주|달|개월|년|원|만)|몇|며칠|하루|한참|많은|꽤|오랜|적지)/.test(next)
        && others.some(x => /^(걸렸|걸린|걸리|걸려|걸릴|들었|든다|드는|들어|들|소요|필요|쓰였|썼|허비)/.test(x))) {
        return { to: core.slice(0, -1) + ' 데', why: "일이나 경우를 뜻하는 '데'는 의존 명사라 앞말과 띄어 씁니다", kind: '띄어쓰기' };
    }
    // 사달(사고)·사단(일의 실마리)
    if (core === '사단이' && /^(났|나|날|난)/.test(next)) return out('사달이', "사고나 탈은 '사달'입니다 ('사달이 나다')");
    // 무치다: '나물을 묻쳐서' → 무쳐서 (음식이 아니면 사전 단계에서 '묻혀서'로 고친다)
    if (/^묻(쳐|쳤|치|친|칠|침|칩)/.test(core) && before.some(x => SEASON_OBJECT.test(x))) {
        return out('무' + core.slice(1), "나물 등을 양념에 버무리는 것은 '무치다'입니다");
    }
    // 닫히다: '문이 닫쳤다' → 닫혔다 ('닫치다'는 힘주어 닫는 것이라 '-을/-를'이 있어야 한다)
    if (/^닫(쳤|쳐|친|칠|침)/.test(core) && !objectBefore) {
        return out('닫' + String.fromCharCode(core.charCodeAt(1) + (18 - 14) * 588) + core.slice(2), "저절로 닫힌 것은 '닫히다'입니다 ('닫치다'는 힘주어 닫는 것)");
    }
    // 놀라다: '너무 놀랬다' → 놀랐다 ('친구를 놀래 주었다'처럼 남을 놀라게 한 것은 그대로)
    if (/^놀(랬|래|램)/.test(core) && !objectBefore && !/^(주|줬|줄|준|줍|드리|드렸)/.test(next)) {
        const to = /^놀랬/.test(core) ? '놀랐' + core.slice(2) : /^놀램/.test(core) ? '놀람' + core.slice(2)
            : /^놀래(서|요|도|고|며|면)?$/.test(core) ? '놀라' + core.slice(2) : null;
        if (to) return out(to, "스스로 놀란 것은 '놀라다'라서 '놀랐다·놀라서'로 씁니다 ('놀래다'는 남을 놀라게 하는 것)");
    }
    // 가다: '교회에 갈려고' → 가려고 ('칼을 숫돌에 갈려고'처럼 갈 것이 있으면 그대로)
    if (/^갈려(고|면|는|던)/.test(core) && /(에|에는|로|으로|에게|한테|까지)$/.test(prev) && !objectBefore) {
        return out('가' + core.slice(1), "'가다'에 '-려고'가 붙으면 '가려고'입니다");
    }
    // 이따가: '있다가 봐' → 이따가 봐 ('집에 있다가 나갔다'는 그대로)
    if ((core === '있다가' || core === '있다') && (!prev || /^(그럼|그러면|그래|우리|나|내가|제가|저|너|네가|엄마|아빠|그럼요)$/.test(prev))
        && /^(봐|보자|봬|뵐|뵙|만나|연락|전화|얘기|이야기|할게|갈게|올게|먹자|하자|가자|오자|줄게)/.test(next)) {
        return out(core === '있다가' ? '이따가' : '이따', "'조금 뒤에'라는 뜻이면 '이따가'로 씁니다");
    }
    // 일부러: '일부로 그런 거 아니야' → 일부러 ('재산의 일부로'는 그대로)
    if (core === '일부로' && !/의$/.test(prev)
        && /^(그런|그랬|그러|그렇|한|했|하|안|못|늦|모른|피|져|틀|저런|이런|천천히|크게|작게|일찍|그냥|아무|티|숨|넘어|떨어|놓|기다|참|웃|울|말|모르)/.test(next)) {
        return out('일부러', "'일부러'(굳이 마음먹고)가 맞는 말입니다 ('일부로'는 '한 부분으로')");
    }
    // 낫다: '감기가 빨리 낳았으면' → 나았으면 / 낳다: '아기를 나았다' → 낳았다
    if (/^낳/.test(core) && before.some(x => DISEASE.test(x)) && !before.some(x => BIRTH_OBJECT.test(x))) {
        const to = swapStem(core, [['낳았', '나았'], ['낳아', '나아'], ['낳으', '나으'], ['낳을', '나을'], ['낳은', '나은'], ['낳', '낫']]);
        return out(to, "병이 고쳐지는 것은 '낫다'라서 '나았다·낫기를'로 씁니다 ('낳다'는 아기를 낳는 것)");
    }
    if (BIRTH_OBJECT.test(prev) && /^(나았|나아|낫|나을|나은|나으)/.test(core)) {
        const to = swapStem(core, [['나았', '낳았'], ['나아', '낳아'], ['나을', '낳을'], ['나은', '낳은'], ['나으', '낳으'], ['낫', '낳']]);
        return out(to, "아기를 세상에 내놓는 것은 '낳다'입니다");
    }
    // 맞히다: '정답을 맞췄다' → 맞혔다 (답이 맞게 한 것. '맞추다'는 서로 비교해 보는 것)
    if (/^(정답|문제|퀴즈|과녁|정곡|수수께끼)(을|를|도|까지)$/.test(prev) && /^맞(추|췄|춰|춘|출|춥)/.test(core)) {
        return out(swapStem(core, [['맞췄', '맞혔'], ['맞춰', '맞혀'], ['맞춘', '맞힌'], ['맞출', '맞힐'], ['맞춥', '맞힙'], ['맞추', '맞히']]),
            "답을 맞게 한 것은 '맞히다'입니다 ('맞추다'는 서로 비교해 보는 것)");
    }
    // 부치다·붙이다: '편지를 붙였다' → 부쳤다, '전을 붙였다' → 부쳤다, '우표를 부쳤다' → 붙였다
    if (/^(편지|소포|택배|우편물|엽서|짐|전|부침개|빈대떡|김치전|파전|녹두전|호떡)(를|을|도)$/.test(prev) && /^붙(이|여|였|인|일|입|치|쳐|쳤|친|칠|칩)/.test(core)) {
        return out(swapStem(core, [['붙였', '부쳤'], ['붙여', '부쳐'], ['붙인', '부친'], ['붙일', '부칠'], ['붙입', '부칩'], ['붙이', '부치'],
            ['붙쳤', '부쳤'], ['붙쳐', '부쳐'], ['붙친', '부친'], ['붙칠', '부칠'], ['붙칩', '부칩'], ['붙치', '부치']]),
            "물건을 보내거나 전을 부치는 것은 '부치다'입니다");
    }
    if (/^(우표|스티커|반창고|포스트잇|테이프|파스|밴드|메모|라벨|전단|벽보)(를|을|도)$/.test(prev) && /^부(치|쳐|쳤|친|칠|칩)/.test(core)) {
        return out(swapStem(core, [['부쳤', '붙였'], ['부쳐', '붙여'], ['부친', '붙인'], ['부칠', '붙일'], ['부칩', '붙입'], ['부치', '붙이']]),
            "맞닿게 하는 것은 '붙이다'입니다");
    }
    // 다르다: '생각이 틀리다', '나랑 틀려' → 다르다 ('틀리다'는 맞지 않은 것)
    // '생각이 틀렸다'(잘못 생각함)와 구별하려고, 견주는 말(나랑·너와·서로)이 있을 때만 본다
    // ('-과'는 결과·효과처럼 '과'로 끝나는 명사와 헷갈려 보지 않는다)
    const compared = others.some(x => /[가-힣](와|랑|이랑|하고|보다)$/.test(x) || /^(서로|각자|다들)$/.test(x));
    if (((DIFFER_SUBJECT.test(prev) && compared) || /[가-힣](와|랑|이랑|하고)$/.test(prev)) && /^틀(리|려|린|렸|릴|립)/.test(core)) {
        return out(swapStem(core, [['틀렸', '달랐'], ['틀려', '달라'], ['틀린', '다른'], ['틀릴', '다를'], ['틀립', '다릅'], ['틀리', '다르']]),
            "같지 않은 것은 '다르다'입니다 ('틀리다'는 맞지 않은 것)");
    }
    // 결제·결재: 돈을 치르는 것은 '결제', 윗사람이 승인하는 것은 '결재'
    if (/^결재/.test(core) && others.some(x => PAYMENT.test(x)) && !others.some(x => APPROVAL.test(x))) {
        return out('결제' + core.slice(2), "돈을 치르는 것은 '결제'입니다 ('결재'는 윗사람이 승인하는 것)");
    }
    if (/^결제/.test(core) && others.some(x => APPROVAL.test(x)) && !others.some(x => PAYMENT.test(x))) {
        return out('결재' + core.slice(2), "윗사람이 승인하는 것은 '결재'입니다 ('결제'는 돈을 치르는 것)");
    }
    // 반드시: '반듯이 해야 한다' → 반드시 ('반듯이 앉다'는 그대로)
    if (core === '반듯이' && /^(해야|할|지켜|기억|필요|오|와|갈|돌아|이루|성공|이기|보답|갚|만나|연락|하겠|해|될|되|올|이길|응답|이뤄|좋아|잘|다시|꼭)/.test(next)
        && !/^(앉|서|놓|눕|세|펴|걸|누|섰|자라|세워|누워|쌓|접|개)/.test(next)) {
        return out('반드시', "'틀림없이 꼭'이라는 뜻이면 '반드시'입니다 ('반듯이'는 비뚤지 않게)");
    }
    // 가리키다·가르치다: '가르키다'는 없는 말
    if (/^가르(키|켜|켰|킨|킬)/.test(core)) {
        const all = [...others];
        const dir = all.some(x => /(손가락|방향|쪽|곳|시계|화살표|표지판|하늘|별|지도|위치|시각|시침|분침)/.test(x));
        const teach = all.some(x => /(학생|아이|영어|수학|공부|피아노|성경|말씀|방법|운전|수영|한글|노래|요리|기술|제자|주일학교|교회학교)/.test(x));
        if (dir && !teach) return out(swapStem(core, [['가르켰', '가리켰'], ['가르켜', '가리켜'], ['가르킨', '가리킨'], ['가르킬', '가리킬'], ['가르키', '가리키']]),
            "방향이나 대상을 짚는 것은 '가리키다'입니다");
        if (teach && !dir) return out(swapStem(core, [['가르켰', '가르쳤'], ['가르켜', '가르쳐'], ['가르킨', '가르친'], ['가르킬', '가르칠'], ['가르키', '가르치']]),
            "지식을 알려 주는 것은 '가르치다'입니다");
    }
    // 로서·로써: '부모로써' → 부모로서 (자격·지위는 '로서', 수단·도구는 '로써')
    const r = ROLE_LOSSEO.exec(core);
    if (r) return out(core.replace(/(으로|로)써/, '$1서'), "자격이나 지위를 나타낼 때는 '-로서'를 씁니다 ('-로써'는 수단·도구)");
    if (core === '이로서') return out('이로써', "'이것으로써'라는 뜻이면 '이로써'입니다");
    // 날아가다: '바람에 날라갔다' → 날아갔다 ('짐을 날라 갔다'처럼 나른 것은 그대로)
    if (/^날라(가|갔|간|갈|와|왔|온|올|다니|다녔)/.test(core) && !objectBefore) {
        return out('날아' + core.slice(2), "공중으로 나는 것은 '날다'라서 '날아가다'로 씁니다 ('날라'는 '나르다')");
    }
    return null;
}

// 늘 앞말에 붙여 쓰는 조사·접미사 (나 처럼 → 나처럼, 3시 까지 → 3시까지, 우리 끼리 → 우리끼리)
const BOUND = /^(처럼|부터|까지|에게서|에게|에서부터|에서|으로서|으로써|으로부터|으로|로서|로써|한테서|한테|께서|끼리|쯤|짜리|어치)(은|는|도|만|요|이|가|을|를|의|라도|이나|나|에|에서|이다|이야|이에요|예요|입니다)?$/;
// '씩'은 수량 뒤에서만 붙인다 ('씩 웃었다'는 그대로)
const COUNTABLE = /^([0-9]+.*|하나|둘|셋|넷|다섯|여섯|일곱|여덟|아홉|열|조금|몇|한두|두세|서너|.*(개|명|번|장|권|잔|마리|시간|분|쪽|줄|그릇|사람|가지|개월|주|달|일|년))$/;
// '째'는 단위 뒤에서만 붙인다
const ORDINAL_UNIT = /(번|개|명|주|일|달|년|해|날|잔|그릇|권|장|시간|차례|바퀴)$/;
// '-지 않다'를 '-지 안다'로 쓴 것 (먹지 안았다 → 먹지 않았다)
const NOT_AN = /^안(?=았|아|다|고|는|으|을|은|게|기|지|도|네|니|습|죠|잖|겠)/;
// '-ㄴ 지 (오래)': 지난 동안을 나타내는 '지'는 띄어 쓴다 (결혼한지 10년 → 결혼한 지 10년)
const DURATION = /^(([0-9]+|[일이삼사오육칠팔구십백]+|한|두|세|네|다섯|여섯|일곱|여덟|아홉|열|몇|수십|수)(년|해|달|개월|주|주일|일|날|시간|분|초)|며칠|오래(?=되|됐|된|다|이다|야|예요|입니다)|벌써|어느덧|어언)/;
// '-ㄴ지'가 어미인 흔한 말 (누군지 몰라 · 어떤지 궁금해) — 뒤에 때를 나타내는 말이 와도 띄우지 않는다
const WHETHER = /(어떤지|누군지|뭔지|왠지|웬지|인지|건지|던지|는지)$/;

/**
 * 두 낱말에 걸친 규칙 — [{ i, j, to, why, valid?, invalid? }] (words[i]의 core 처음부터 words[j]의 core 끝까지를 to로)
 * valid·invalid가 있으면 사전에서 그 말이 각각 있고·없을 때만 고친다.
 *  - 몇 일 → 며칠, 그리고 나서 → 그러고 나서, 할 수록 → 할수록, 수 밖에 → 수밖에
 *  - 나 처럼 → 나처럼 (늘 붙여 쓰는 조사), 하나 씩 → 하나씩
 *  - 먹지 안았다 → 먹지 않았다, 결혼한지 10년 → 결혼한 지 10년, 가던지 말던지 → 가든지 말든지
 *  - the the → the
 */
// 뒷가지 '-드리다·-받다·-당하다'가 붙는 말 (기도드리다·사랑받다·무시당하다) — 사전에 한 낱말로 오른 것만
const DRI_NOUNS = new Set(['감사', '축하', '말씀', '부탁', '인사', '기도', '예배', '사과', '안내', '연락', '제사', '문안', '세배', '공양', '축원']);
const BAT_NOUNS = new Set(['사랑', '인정', '존경', '축복', '용서', '위로', '상처', '주의', '오해', '칭찬', '보호', '대접', '치료', '허락', '지원', '훈련', '세례', '버림',
    '구원', '은혜', '교육', '초대', '격려', '환영', '대우', '주목', '방해', '간섭']);
const DANG_NOUNS = new Set(['무시', '거절', '이용', '공격', '해고', '폭행', '체포', '비난', '망신', '배신', '사기', '강요', '차별', '외면', '협박', '납치', '추방', '침략', '봉변']);
// 붙여 써야 하는 두 낱말 [앞말, 뒷말 꼴] (끊임 없이 → 끊임없이, 지난 주 → 지난주)
// [앞말, 뒷말 꼴, 알려 줄 한 낱말 (없으면 앞말 + 뒷말 첫 글자)]
const FIXED_JOINS = [
    ['끊임', /^없이$/, '끊임없이'], ['변함', /^없(이|는|다|었)/, '변함없다'], ['정신', /^없이$/, '정신없이'], ['눈치', /^(채|챘|챈|챌|채지|채고)/, '눈치채다'],
    ['마음', /^속(에|으로|의|에서|을|이|은|도)?$/, '마음속'], ['스며', /^(들|든|들었|들어|드는)/, '스며들다'], ['밤', /^(늦게|늦은|늦도록|늦었)/, '밤늦다'],
    ['지켜', /^(보|봤|본|볼|봐|보았|보며|보고|보는)/, '지켜보다'], ['힘', /^(들|든|드|들었|들어서|들어요|들지|들고|들게|듭)(?!어가|어간|어갔|어갈)/, '힘들다'],
    ['일', /^주일(간|째|이|을|은|도|에|동안)?$/, '일주일'], ['점심', /^시간(에|이|을|은|도|에는)?$/, '점심시간'], ['빈', /^칸(에|을|이|은|도)?$/, '빈칸'],
    ['오래', /^(된|되|됐|되었)/, '오래되다'], ['오래', /^(전|전에|전부터|전의|전이)$/, '오래전'], ['똑', /^(같|같이|같은|같다|같아)/, '똑같다'],
    ['잘', /^(생긴(?!다)|생겼|생기셨|생겨서)/, '잘생기다'], ['못', /^(생긴(?!다)|생겼|생기셨|생겨서)/, '못생기다'],
    ['재미', /^있/, '재미있다'], ['재미', /^없/, '재미없다'], ['맛', /^있/, '맛있다'], ['맛', /^없/, '맛없다'], ['멋', /^있/, '멋있다'], ['멋', /^없/, '멋없다'],
    ['상관', /^없/, '상관없다'], ['관계', /^없/, '관계없다'], ['여기', /^저기/, '여기저기'], ['이것', /^저것/, '이것저것'], ['이런', /^저런/, '이런저런'], ['이리', /^저리/, '이리저리'],
    ['구석', /^구석/, '구석구석'], ['이곳', /^저곳/, '이곳저곳'], ['이래', /^저래/, '이래저래'], ['그럭', /^저럭/, '그럭저럭'],
    ['불러', /^(일으키|일으켜|일으켰|일으킨|일으킬)/, '불러일으키다'], ['얽히고', /^(설키|설켜|설킨)/, '얽히고설키다'],
    ['이', /^외(에|의|에는|에도)?$/, '이외'], ['무의식', /^중(에|에도)?$/, '무의식중'], ['얼마', /^만큼(이|의|은)?$/, '얼마만큼'], ['다음', /^번(에|에는|에도|엔|의)?$/, '다음번'],
    ['지난', /^(번|주|달|해|밤)(에|에는|에도|의|엔|부터|까지|보다)?$/],
];
// 그 밖의 두 낱말 고침 [앞말, 뒷말, 바꾼 글, 까닭]
const PAIR_FIXES = [
    [/^염치$/, /^불구하(고|여)/, (a, b) => '염치 불고하' + b.slice(3), "'염치를 돌보지 않고'의 뜻은 '염치 불고하고'입니다"],
    [/^(제|내)$/, /^자신(이|을|은|도|의|에게|만|과)?$/, (a, b) => (a === '제' ? '저 ' : '나 ') + b, "'자신' 앞에는 '나·저'를 씁니다 ('나 자신')"],
    [/^곤혹(을|도)$/, /^(치르|치렀|치러|당하|당했|겪)/, (a, b) => '곤욕' + a.slice(2) + ' ' + b, "심한 모욕이나 고통은 '곤욕(困辱)을 치르다'입니다"],
    [/^겉잡을$/, /^수/, (a, b) => '걷잡을 ' + b, "'걷잡다'(바로잡다)가 맞는 말입니다 ('걷잡을 수 없다')"],
    [/^홀몸이$/, /^아니/, (a, b) => '홑몸이 ' + b, "아이를 가진 몸은 '홑몸이 아니다'입니다"],
    [/^빚(이|을)$/, /^(나|났|난|발하|발했|비추|비치)/, (a, b) => '빛' + a.slice(1) + ' ' + b, "환하게 비치는 것은 '빛'입니다"],
    [/^빛(을|이|도|은)$/, /^(갚|지고|졌|지다|져서)/, (a, b) => '빚' + a.slice(1) + ' ' + b, "갚아야 할 돈은 '빚'입니다"],
    [/^(목|목이)$/, /^메(였|여|인|이)/, (a, b) => a + ' ' + b.replace(/^메였/, '메었').replace(/^메여/, '메어').replace(/^메인/, '멘').replace(/^메이/, '메'), "목이 막히는 것은 '메다'라 '메었다·멘'입니다"],
    [/^(눈|두 눈)을$/, /^지긋이$/, (a, b) => a + ' 지그시', "슬며시 힘을 주는 모양은 '지그시'입니다"],
    [/^(나이가|나이도)$/, /^지그시$/, (a, b) => a + ' 지긋이', "나이가 꽤 많은 것은 '지긋이'입니다"],
];
// 형용사 + '-지' (좋지 않은)
const ADJ_JI = /^(좋|싫|많|적|작|크|길|짧|넓|높|낮|깊|쉽|어렵|덥|춥|같|괜찮|예쁘|바쁘|아프|슬프|기쁘|아름답|행복하|편하|불편하|건강하|중요하|필요하|가능하|깨끗하|조용하|따뜻하|피곤하|심심하|궁금하|미안하|친하|착하|똑똑하|이상하|정확하|확실하|분명하|충분하|부족하|익숙하|낯설|가볍|무겁|빠르|느리|멀|가깝|귀찮|외롭|즐겁|반갑|고맙|무섭|부럽|싱싱하|성실하|겸손하|정직하)지$/;
// '-의' 다음에 올 수 없는 이어 주는 풀이말 끝 (들고·와서·하며·먹다가)
const SUBJ_NEXT = /[가-힣](고|어서|아서|여서|해서|며|면서|다가|지만|도록|려고|자마자)$/;
// 명사 + '이다'의 이음 꼴 (김밥이었고·공통점이라고·특징이며) — '-의' 뒤에 와도 된다
const COPULA_LINK = /[가-힣](이었고|였고|이고|이며|이었으며|였으며|이지만|이었지만|였지만|이라서|이어서|여서|이면서|이라고|라고|이었다가|였다가)$/;
// 앞말과 붙여 한 낱말이 되는 말 (그 동안 → 그동안, 이 번 → 이번). 뒤에 조사만 붙은 꼴까지 ('그 때부터')
const ONE_WORD_AFTER = {
    '그': ['동안', '때', '중', '날', '곳', '간', '만큼', '다음', '새'],
    '이': ['때', '곳', '날', '번', '만큼', '다음'],
    '저': ['곳', '번'],
    '한': ['동안', '때'],
    '어느': ['새', '덧', '결', '틈'],
};
export function pairRules(words) {
    const out = [];
    // 성경 구절(옛말 꼴이 있는 줄)은 본문의 띄어쓰기를 그대로 둔다 ('그 날로 족하니라', '그 중의 제일은')
    const scripture = words.some(w => w.lang === 'ko' && ARCHAIC.test(w.core));
    for (let j = 1; j < words.length; j++) {
        const p = words[j - 1], w = words[j];
        if (p.b !== p.cb || w.a !== w.ca) continue;   // 사이에 문장 부호가 있으면 건너뛴다
        const push = (to, why) => out.push({ i: j - 1, j, to, why });
        if (p.lang === 'en' && w.lang === 'en') {
            if (p.core.toLowerCase() === w.core.toLowerCase() && EN_DUP.has(w.core.toLowerCase())) push(p.core, '같은 낱말을 두 번 썼습니다');
            continue;
        }
        if (w.lang === 'ko' && p.core && BOUND.test(w.core) && p.lang !== 'en') { push(p.core + w.core, `${topic(w.core.replace(BOUND, '$1'))} 앞말에 붙여 씁니다`); continue; }
        if (w.lang === 'ko' && /^씩(은|만|이라도)?$/.test(w.core) && COUNTABLE.test(p.core)) { push(p.core + w.core, "'-씩'은 앞말에 붙여 씁니다"); continue; }
        if (w.lang === 'ko' && /^째(로|는|도|야)?$/.test(w.core) && ORDINAL_UNIT.test(p.core)) { push(p.core + w.core, "'-째'는 앞말에 붙여 씁니다"); continue; }
        if (p.lang === 'ko' && /[가-힣]지$/.test(p.core) && jongOf(p.core[p.core.length - 2]) === JONG_N && !WHETHER.test(p.core)
            && DURATION.test(w.core)) {
            out.push({ i: j - 1, j, to: p.core.slice(0, -1) + ' 지 ' + w.core, why: "지난 동안을 나타내는 '지'는 의존 명사라 띄어 씁니다",
                valid: [p.core.slice(0, -1)], invalid: [p.core] });
            continue;
        }
        if (p.lang !== 'ko' || w.lang !== 'ko') continue;
        const one = !scripture && ONE_WORD_AFTER[p.core] && ONE_WORD_AFTER[p.core].find(x => w.core.startsWith(x) && (w.core === x || PARTICLE_TAIL.test(w.core.slice(x.length))));
        if (one) { push(p.core + w.core, `${topic(p.core + one)} 한 낱말이라 붙여 씁니다`); continue; }
        if (p.core === '한번' && w.core === '더') { push('한 번 더', "횟수를 셀 때는 '한 번'으로 띄어 씁니다"); continue; }
        // 뒷가지 '-드리다·-받다·-당하다'는 앞말에 붙여 쓴다 (감사드립니다·사랑받다·무시당하다)
        const suffix = /^(드리|드려|드렸|드린|드릴|드립|드림)/.test(w.core) ? DRI_NOUNS : /^(받|받아|받았)/.test(w.core) ? BAT_NOUNS : /^(당하|당해|당했|당한|당할|당합)/.test(w.core) ? DANG_NOUNS : null;
        const tail = (fixed) => (fixed && !/\s/.test(fixed.to) ? fixed : null);
        if (suffix && suffix.has(p.core)) {
            const more = tail(fixKoreanWord(w.core, '', ''));
            push(p.core + (more ? more.to : w.core), `'-${w.core[0] === '드' ? '드리다' : w.core[0] === '받' ? '받다' : '당하다'}'는 앞말에 붙여 씁니다` + (more ? ' · ' + more.whys.join(' · ') : ''));
            continue;
        }
        // ('아무 상관 없다'처럼 '아무'가 꾸미면 띄어 쓴다)
        const fj = words[j - 2] && words[j - 2].core === '아무' ? null : FIXED_JOINS.find(([a, b]) => p.core === a && b.test(w.core));
        if (fj) { push(p.core + w.core, `${topic(fj[2] || p.core + w.core.slice(0, 1))} 한 낱말이라 붙여 씁니다`); continue; }
        // 꾸며 주는 말 + 듯·만·법·뻔·척·체 + 하다 → '듯하다' (올 듯하다·먹을 만하다·넘어질 뻔했다·아는 척했다)
        const before = words[j - 2] && words[j - 2].lang === 'ko' ? words[j - 2].core : '';
        if (/^(듯|만|법|뻔|척|체)$/.test(p.core) && /^(하|했|한|할|합|해|함)/.test(w.core) && before && (endsWithL(before[before.length - 1])
            || (/^(듯|척|체)$/.test(p.core) && (jongOf(before[before.length - 1]) === JONG_N || /[는던]$/.test(before))))) {
            push(p.core + w.core, `'${p.core}하다'는 한 낱말이라 붙여 씁니다`);
            continue;
        }
        // 우리말 수는 붙여 쓴다 (스물두·열한)
        if (/^(열|스물|서른|마흔|쉰|예순|일흔|여든|아흔)$/.test(p.core) && /^(한|두|세|네|다섯|여섯|일곱|여덟|아홉|하나|둘|셋|넷)(째|번째|이|을|은|도|가|를|는)?$/.test(w.core)) {
            push(p.core + w.core, '열·스물 따위와 그 뒤의 수는 붙여 씁니다');
            continue;
        }
        if (/[가-힣]$/.test(p.core) && endsWithL(p.core[p.core.length - 1]) && w.core === '게요') { push(p.core + w.core, "'-ㄹ게요'는 한 낱말로 붙여 씁니다"); continue; }
        if (p.core === '큰' && /^일(이다|이야|이에요|이네|났다|났어|났네|났구나|나|입니다)$/.test(w.core)) { push('큰' + w.core, "'큰일'(크게 걱정할 일)은 한 낱말입니다"); continue; }
        if (p.core === '가능한' && /^(빨리|많이|일찍|자주|짧게|적게|쉽게|크게|빠르게|신속히|조속히)$/.test(w.core)) { push('가능한 한 ' + w.core, "'할 수 있는 만큼'의 뜻은 '가능한 한'입니다"); continue; }
        if (/^(조차|마저|커녕|은커녕|는커녕)(도|는|요)?$/.test(w.core) && !/[는은던]$/.test(p.core) && !ADVERBS.has(p.core)) { push(p.core + w.core, `${topic(w.core.replace(/(도|는|요)$/, ''))} 조사라 앞말에 붙여 씁니다`); continue; }
        if (w.core === '마다' && !/^(않|안|하|했|한)/.test(words[j + 1] ? words[j + 1].core : '') && !/[는은던]$/.test(p.core)) { push(p.core + '마다', "'마다'는 조사라 앞말에 붙여 씁니다"); continue; }
        if ((/^(답게|답다|답고|다워|다웠)/.test(w.core) || (w.core === '답지' && /^(않|못)/.test(words[j + 1] ? words[j + 1].core : ''))) && p.core.length >= 2 && !/[는은던을]$/.test(p.core)) { push(p.core + w.core, "'-답다'는 앞말에 붙여 씁니다"); continue; }
        if (w.core === '밖에' && !/^(그|이|저|수)$/.test(p.core) && /^(없|안|못|모르|몰라)/.test(words[j + 1] ? words[j + 1].core : '')) { push(p.core + '밖에', "'밖에'(오직)는 조사라 앞말에 붙여 씁니다"); continue; }
        // 형용사 + '-지 않는' → '-지 않은' (좋지 않는 → 좋지 않은)
        if (ADJ_JI.test(p.core) && /^않는/.test(w.core)) { push(p.core + ' 않은' + w.core.slice(2), "형용사 뒤에서는 '-지 않은'으로 씁니다"); continue; }
        const only = /^(.+)뿐이$/.exec(p.core);
        if (only && /^(없|안|못|모르|몰라)/.test(w.core)) { push(only[1] + '밖에 ' + w.core, "뒤에 '없다·않다'가 오면 '-밖에'를 씁니다"); continue; }
        const pair2 = PAIR_FIXES.find(([a, b]) => a.test(p.core) && b.test(w.core));
        if (pair2) { push(pair2[2](p.core, w.core), pair2[3]); continue; }
        if (/[가-힣]의$/.test(p.core) && p.core.length >= 2 && /^(대해|대한|대하여|대해서|관해|관한|관하여|관해서|의해|의한|의하여|의해서)/.test(w.core)) {
            push(p.core.slice(0, -1) + '에 ' + w.core, `'${w.core.replace(/^(대|관|의).*/, '$1')}하다' 앞에는 '-에'를 씁니다 ('-에 ${w.core.replace(/^(대|관|의).*/, '$1')}해')`);
            continue;
        }
        // '승려의 들고 있던' → '승려가 들고 있던': '-의' 뒤에는 명사가 와야 한다. 뒤가 이어 주는 풀이말이면 주어로 고친다
        // (사전으로 앞말이 명사이고 뒷말이 명사가 아닌지 확인한다 — '회사의 광고'처럼 '-고'로 끝나는 명사는 그대로)
        const nominal = words[j + 1] && /[가-힣](음|기)(이|가|을|를|은|는|도|만|의|에|으로|이라고|이라는|이다)?$/.test(words[j + 1].core);
        if (/[가-힣]의$/.test(p.core) && p.core.length >= 3 && w.core.length >= 2 && SUBJ_NEXT.test(w.core) && !COPULA_LINK.test(w.core) && !nominal && !scripture) {
            const stem = p.core.slice(0, -1);
            const subj = stem + (hasJong(stem[stem.length - 1]) ? '이' : '가');
            out.push({ i: j - 1, j, to: subj + ' ' + w.core, why: "뒤에 오는 풀이말의 주어이므로 '-이/-가'를 씁니다 ('-의' 뒤에는 명사가 옵니다)",
                valid: [p.core, subj, w.core], invalid: [w.core + '을', w.core + '를', w.core + '의'] });
            continue;
        }
        if (p.core === '몇') {
            const m = /^일(이|을|은|간|째|동안|만에|부터|까지|에|이나|이면|이라도|도)?$/.exec(w.core);
            if (m) push('며칠' + (m[1] || ''), "'몇 일'이 아니라 '며칠'이 표준어입니다");
        } else if (p.core === '그리고' && /^나(서|니|면|자)/.test(w.core)) {
            push('그러고 ' + w.core, "'그렇게 하고 나서'라는 뜻이면 '그러고 나서'입니다");
        } else if (w.core === '수록' && endsWithL(p.core[p.core.length - 1])) {
            push(p.core + '수록', "'-ㄹ수록'은 앞말에 붙여 씁니다");
        } else if (p.core === '수' && /^밖에(는|도)?$/.test(w.core)) {
            push('수' + w.core, "'밖에'는 조사라 앞말에 붙여 씁니다");
        } else if (/지$/.test(p.core) && p.core.length >= 2 && NOT_AN.test(w.core)) {
            push(p.core + ' 않' + w.core.slice(1), "'-지 않다'의 '않-'은 '아니하-'가 줄어든 말입니다");
        } else if (/던지$/.test(p.core) && /^말던지/.test(w.core)) {
            push(p.core.replace(/던지$/, '든지') + ' ' + w.core.replace(/^말던지/, '말든지'), "고르는 뜻일 때는 '-든지'를 씁니다");
        }
    }
    return out;
}

// 한 낱말을 잘못 띄어 쓴 것 (먹 었다 → 먹었다, 공부 했다 → 공부했다)
// 어미·조사로 시작해 홀로는 사전에 없는 조각이거나, '-하다·-되다·-시키다'가 붙는 명사 뒤를 띄운 것
const DO_VERB = /^(하|해|했|합|한|할|함|되|돼|됐|된|될|됩|됨|시키|시켜|시켰|시킨|시킬|시킵)/;
// 부사·이음말로 흔히 쓰여 '-하다'를 붙이면 다른 낱말이 되는 말 (각자 하고 ≠ 각자(刻字)하고, 위해 할 ≠ 위해(危害)할)
const NOT_DO_NOUN = new Set(['각자', '위해', '위하여', '스스로', '각각', '저마다', '직접', '처음', '마지막', '사실', '실제', '대부분', '전부',
    '일부', '대신', '역시', '다시', '정말', '진짜', '때문', '덕분', '모두', '서로', '다들', '이미', '아직', '오늘', '내일', '어제', '지금', '문제']);

/**
 * 붙여 써야 할 두 낱말 후보 — [{ i, j, to, why, valid, invalid }]
 * 사전에서 valid는 모두 있고 invalid는 모두 없을 때만 고친다 (checkLines가 확인한다).
 */
export function joinCandidates(words) {
    const out = [];
    for (let j = 1; j < words.length; j++) {
        const p = words[j - 1], w = words[j];
        if (p.lang !== 'ko' || w.lang !== 'ko' || p.b !== p.cb || w.a !== w.ca) continue;
        const a = p.core, b = w.core, ab = a + b;
        if (ARCHAIC.test(b)) continue;
        const next = words[j + 1] && words[j + 1].a >= w.b ? words[j + 1].core : '';
        // '-하다·-되다·-시키다'가 붙는 명사 + 그 꼴 (기도 했다 → 기도했다). 부사·때·수를 나타내는 말은 빼고 두 글자 이상 명사만
        const verb = DO_VERB.exec(b);
        // '한'은 수를 나타내는 말일 수 있어(말씀 한 구절·공부 한 시간) 뒤에 '것·후·적' 같은 말이 올 때만 본다
        if (verb && a.length >= 2 && !ADVERBS.has(a) && !TIME_DET.has(a) && !NUM_DET.has(a) && !NOT_DO_NOUN.has(a) && (b !== '한' || ADN_DEP.test(next) || next === '지')) {
            const lemma = a + (/^(되|돼|됐|된|될|됩|됨)/.test(b) ? '되다' : /^시/.test(b) ? '시키다' : '하다');
            // '두 배가 된다'·'부자가 된다'의 '-가·-이'는 조사다 — 앞이 명사이면 붙이지 않는다
            const head = a.slice(0, -1);
            const invalid = /[가이]$/.test(a) ? [head + (hasJong(head[head.length - 1]) ? '을' : '를')] : [];
            out.push({ i: j - 1, j, to: ab, why: `'${lemma}'는 한 낱말이라 붙여 씁니다`, valid: [ab, a + '의', a + (hasJong(a[a.length - 1]) ? '을' : '를')], invalid });
            continue;
        }
        // 홀로는 낱말이 아닌 조각 (먹 었다, 읽 었다, 감사합 니다)
        if (ab.length >= 3) {
            out.push({ i: j - 1, j, to: ab, why: '한 낱말이라 붙여 씁니다', valid: [ab], invalid: [b] });
            out.push({ i: j - 1, j, to: ab, why: '한 낱말이라 붙여 씁니다', valid: [ab], invalid: [a] });
        }
    }
    return out;
}

